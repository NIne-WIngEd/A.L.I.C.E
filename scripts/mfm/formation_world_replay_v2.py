def _cut(value, world_id, expected=None):
    C.exact(value, {'schema','world_id','branch_id','sequence','head_sha256','record_sha256'}, 'world cut')
    C.pin(value, value['record_sha256'] if expected is None else expected, 'mfm-world-cut-v1')
    C.require(value['world_id']==world_id, 'foreign world cut')
    C.identifier(value['branch_id']); C.integer(value['sequence']); C.digest(value['head_sha256'])


def _manifest(world, expected, limits):
    C.exact(world, {'schema','world_id','scope','namespace','provenance','ledger_profile','authority_profile','episode_projection_profile','branches','world_sha256'}, 'world')
    C.pin(world,expected,'mfm-longitudinal-world-v2','world_sha256')
    scope=C.scope(world['scope']); C.identifier(world['world_id']); C.identifier(world['namespace'])
    p=world['provenance']
    C.exact(p, {'author_id','generator_family','renderer_family','scenario_families','host_lineage','source_person_lineage','parent_world_refs','rights_refs'}, 'world provenance')
    for name in ('author_id','generator_family','renderer_family'): C.identifier(p[name])
    for name in ('scenario_families','host_lineage','source_person_lineage','parent_world_refs','rights_refs'):
        C.require(type(p[name]) is list and len(set(p[name]))==len(p[name]), 'provenance array differs')
        for item in p[name]: C.identifier(item)
    lp=world['ledger_profile']; ap=world['authority_profile']
    C.exact(lp, {'schema','ledger_schema_version','ledger_id','scope_sha256','created_at','genesis_sha256'}, 'ledger profile')
    ledger_id,scope_sha=C.ledger_store._ledger_identity(scope)
    C.timestamp(lp['created_at'])
    genesis=C.canonical_sha256({'ledger_schema_version':C.ledger.LEDGER_SCHEMA_VERSION,'ledger_id':ledger_id,
        'scope':C.ledger_store._scope_material(scope),'created_at':lp['created_at']})
    C.require(lp=={'schema':'experience-ledger-records-v1','ledger_schema_version':C.ledger.LEDGER_SCHEMA_VERSION,
        'ledger_id':ledger_id,'scope_sha256':scope_sha,'created_at':lp['created_at'],'genesis_sha256':genesis}, 'actual ledger genesis differs')
    C.exact(ap, {'schema','authority_id','authority_generation','prototype_state'}, 'authority profile')
    C.identifier(ap['authority_id']); C.integer(ap['authority_generation'],1)
    C.require(ap['schema']=='claim-prototype-records-v1' and ap['authority_generation']==1 and
        ap['prototype_state']=='reversible_nonproduction','unsupported authority profile')
    C.require(ap['authority_id']=='claim-authority-prototype-'+C.authority._scope_digest(scope,world['namespace'])[:32],
        'actual prototype namespace identity differs')
    world_genesis=C.canonical_sha256({'schema':'mfm-world-genesis-v2','world_id':world['world_id'],
        'scope':world['scope'],'namespace':world['namespace'],'ledger_profile':lp,'authority_profile':ap,'episode_projection_profile':world['episode_projection_profile']})
    C.artifact_ref(world['episode_projection_profile'],limits)
    C.require(type(world['branches']) is list and world['branches'], 'world branches required')
    branches={}
    for branch in world['branches']:
        C.exact(branch, {'branch_id','parent_cut','records'}, 'world branch'); C.identifier(branch['branch_id'])
        C.require(branch['branch_id'] not in branches and type(branch['records']) is list, 'branch collision/records differ')
        if branch['parent_cut'] is not None: _cut(branch['parent_cut'],world['world_id'])
        for row in branch['records']:
            C.exact(row, {'sequence','record_sha256','artifact'}, 'world descriptor')
            C.integer(row['sequence'],1); C.digest(row['record_sha256']); C.artifact_ref(row['artifact'],limits)
        branches[branch['branch_id']]=branch
    flattened={}; active=set()
    def flatten(name):
        C.require(name in branches and name not in active, 'missing/cyclic branch ancestry')
        if name in flattened: return flattened[name]
        active.add(name); branch=branches[name]; parent=branch['parent_cut']; rows=[]
        if parent is not None:
            ancestor=flatten(parent['branch_id']); n=parent['sequence']
            C.require(n<=len(ancestor) and parent['head_sha256']==(world_genesis if n==0 else ancestor[n-1]['record_sha256']), 'parent cut differs')
            rows=list(ancestor[:n])
        for row in branch['records']:
            C.require(row['sequence']==len(rows)+1, 'noncontiguous branch suffix')
            rows.append(row)
        active.remove(name); flattened[name]=rows; return rows
    for name in branches: flatten(name)
    return scope,world_genesis,flattened


def replay_world_prefix_v2(world, *, world_sha256, cut, cut_sha256, read_artifact, limits,
                        contract_binding, contract_binding_sha256):
    binding_v2(contract_binding,contract_binding_sha256)
    scope,genesis,branches=_manifest(world,world_sha256,limits)
    _cut(cut,world['world_id'],cut_sha256)
    C.require(cut['branch_id'] in branches, 'unknown cut branch')
    all_rows=branches[cut['branch_id']]; n=cut['sequence']
    C.require(n<=len(all_rows) and n<=limits.max_records,'complete prefix exceeds limit/missing cut')
    rows=all_rows[:n]
    C.require(cut['head_sha256']==(genesis if n==0 else rows[-1]['record_sha256']), 'cut head differs')
    pins={}; cache={}; consumed=0
    def read(ref):
        nonlocal consumed
        C.artifact_ref(ref,limits); key=ref['artifact_id']
        if key in pins:
            C.require(pins[key]==ref,'immutable artifact key collision'); return cache[key]
        C.require(consumed+ref['bytes']<=limits.max_opened_bytes,'complete prefix bytes exceed explicit limit')
        raw=C.read_bytes(ref,read_artifact,limits); consumed+=len(raw); pins[key]=deepcopy(ref); cache[key]=raw
        return raw
    profile=E._profile(C.parse_json(read(world['episode_projection_profile'])))
    C.require(profile.scope==scope and profile.authority_namespace_id==world['namespace'],'foreign world Episode profile')
    episodes={}; targets={}; episode_operations={}; registrations={}
    previous=genesis; experience_head=world['ledger_profile']['genesis_sha256']; events=set()
    current={}; versions={}; version_digests={}; operations={}; metadata={}; sources={}; visibility={}; position=0
    for descriptor in rows:
        record=C.read_json(descriptor['artifact'],read,limits)
        C.exact(record, {'schema','world_id','scope','namespace','sequence','previous_record_sha256','event','entry_receipt','payload_kind','payload','record_sha256'}, 'world record')
        C.pin(record,descriptor['record_sha256'],'mfm-world-record-v2')
        C.require(record['world_id']==world['world_id'] and record['scope']==world['scope'] and
                  record['namespace']==world['namespace'] and record['sequence']==descriptor['sequence'] and
                  type(record['sequence']) is int and record['previous_record_sha256']==previous,'world record ancestry differs')
        event=ExperienceEvent.from_metadata_record(record['event'])
        C.require(event.metadata_record()==record['event'] and event.scope==scope and event.event_id not in events and
                  set(event.parent_event_ids)<=events,'original event/parent differs')
        receipt_row=record['entry_receipt']; C.exact(receipt_row,{f.name for f in C.fields(ExperienceLedgerEntryReceipt)},'Experience receipt')
        receipt=ExperienceLedgerEntryReceipt(**receipt_row); receipt.validate()
        C.require(receipt.record()==receipt_row and receipt.sequence==descriptor['sequence'] and
                  receipt.event_id==event.event_id and receipt.event_sha256==event.event_sha256 and
                  receipt.previous_entry_sha256==experience_head,'original Experience chain differs')
        kind=record['payload_kind']; payload=record['payload']
        expected_digest=payload.get('source_artifact',{}).get('file_sha256') if kind=='observation' else C.canonical_sha256(payload)
        C.require(event.event_type==kind.replace('_','-') and event.content_digest==expected_digest and event.payload_reference is not None,
                  'event payload binding differs')
        def registration(ref_id,family,identity_kind,digest,original=None,support=()):
            return {'ref_id':ref_id,'family':family,'kind':identity_kind,'scope':world['scope'],'namespace':world['namespace'],
                'record_sha256':digest,'known_at_sequence':descriptor['sequence'],'known_at_entry_sha256':receipt.entry_sha256,
                'world_record_sha256':record['record_sha256'],'world_record_artifact':deepcopy(descriptor['artifact']),
                'original_artifact':deepcopy(original),'supporting_evidence_refs':list(support)}
        def governing(ref):
            result=C.governance(ref,read,limits,scope,world['namespace'])
            C.require(set(result['source_refs'])<=set(sources), 'governance names unavailable source')
            return result
        def rights(refs):
            C.require(type(refs) is list and refs and len(set(refs))==len(refs) and set(refs)<=set(world['provenance']['rights_refs']),
                'Episode registration/governance rights provenance differs')
            for item in refs:C.identifier(item)
        def episode_governance(ref):
            result=C.read_json(ref,read,limits)
            C.exact(result,{'schema','scope','namespace','episode_id','episode_sha256','action','expected_predecessor_id',
                'member_ancestry_sha256','rights_refs','origin','record_sha256'},'Episode governance')
            C.pin(result,result['record_sha256'],'mfm-world-episode-governance-v1')
            C.require(result['scope']==world['scope'] and result['namespace']==world['namespace'] and
                result['origin']=='research_explicit_records','foreign/unsupported Episode governance')
            C.identifier(result['episode_id'])
            if result['expected_predecessor_id'] is not None:C.identifier(result['expected_predecessor_id'])
            for key in ('episode_sha256','member_ancestry_sha256'):
                if result[key] is not None:C.digest(result[key])
            rights(result['rights_refs']);return result
        def episode_agreement(gov,action,original):
            members={k:original[k] for k in ('member_evidence_ids','member_claim_version_ids','member_candidate_ids','mission_node_ids','participant_ids')}
            C.require(gov['action']==action and gov['episode_id']==original['episode_id'] and gov['episode_sha256']==original['episode_sha256'] and
                gov['expected_predecessor_id']==original['supersedes_episode_id'] and gov['member_ancestry_sha256']==C.canonical_sha256(members),
                'Episode supplied governance/original differs')
        if kind=='observation':
            C.exact(payload, {'registration','source_artifact','source_rights_ref','observed_at','speaker_ref','subject_ref','epistemic_role','modality','locator'}, 'observation')
            regrow=payload['registration']; C.exact(regrow, {'evidence','object_ref','registration_sha256'}, 'registration')
            reg=C.registration(regrow); evidence=reg.evidence
            C.require(evidence.metadata_record()==regrow['evidence'] and reg.registration_sha256==regrow['registration_sha256'] and
                evidence.scope==scope and evidence.authority_namespace_id==world['namespace'] and
                evidence.ref_id not in sources and evidence.content_digest==payload['source_artifact']['file_sha256'] and
                reg.object_ref==payload['source_artifact']['artifact_id'] and evidence.role==payload['epistemic_role'] and
                evidence.modality==payload['modality'] and evidence.subject_ref==payload['subject_ref'] and
                evidence.speaker_ref==payload['speaker_ref'] and evidence.observed_at==payload['observed_at'] and
                set(evidence.parent_refs)<=set(sources),'observation registration differs')
            C.artifact_ref(payload['source_artifact'],limits); C.identifier(payload['source_rights_ref'])
            C.require(payload['source_rights_ref'] in world['provenance']['rights_refs'],'observation rights ancestry differs')
            if payload['speaker_ref'] is not None:C.identifier(payload['speaker_ref'])
            if payload['observed_at'] is not None:C.timestamp(payload['observed_at'])
            C.require(payload['modality']=='text' and payload['locator'] is None, 'native source profile unsupported')
            sources[evidence.ref_id]=deepcopy(payload); visibility[evidence.ref_id]='present'
            registrations[('evidence',evidence.ref_id)]=registration(evidence.ref_id,'registered-source-v1','evidence',
                reg.registration_sha256,support=evidence.parent_refs)
        elif kind=='claim_commit':
            t=C.claim_transition(payload,read,limits,scope,world['namespace'],world['authority_profile'])
            governing(payload['governance_ref']); req=t['request']; r=t['receipt']; cid=t['identity'].claim_id
            key=req.idempotency_tuple()[:2]; signature={k:deepcopy(v) for k,v in payload.items() if k not in ('append_receipt','governance_ref')}
            if r.idempotent_replay:
                C.require(key in operations and operations[key]['signature']==signature and
                    operations[key]['receipt']=={**r.metadata_record(),'idempotent_replay':False,
                    'receipt_sha256':operations[key]['receipt']['receipt_sha256']}, 'conflicting/unknown idempotent confirmation')
            else:
                C.require(key not in operations and r.store_sequence==position+1, 'idempotency reuse/noncontiguous authority')
                old=current.get(cid); expected=None if old is None else old['records']['version']['claim_version_id']
                C.require(req.expected_current_claim_version_id==expected and
                    r.version_sequence==(1 if old is None else old['records']['version']['version_sequence']+1) and
                    r.projection_generation==(1 if old is None else old['records']['projection']['projection_generation']+1), 'actual current version/counters differ')
                if old is not None: C.require(old['records']['identity']==t['identity'].metadata_record(), 'Claim original identity changed')
                C.require(set(req.correction_of)<=set(versions) and set(req.version_envelope.supersedes)<=set(versions), 'unavailable correction ancestry')
                C.require(set(req.version_envelope.source_records)-{cid} <= set(sources)|set(versions), 'unavailable Claim source ancestry')
                C.require(payload['action']!='append' or old is None, 'append cannot silently revise existing Claim')
                current[cid]={'ref_id':cid,'records':{k:t[k].metadata_record() for k in ('identity','version','projection')},
                    'originals':{k:{'artifact':deepcopy(payload[k]),'base64':b64encode(raw).decode('ascii')} for k,raw in t['originals'].items()},
                    'append_receipt':deepcopy(payload['append_receipt']),'governance_ref':deepcopy(payload['governance_ref'])}
                versions[t['version'].claim_version_id]=cid; version_digests[t['version'].claim_version_id]=t['version'].version_sha256; position=r.store_sequence
                registrations[('claim_versions',t['version'].claim_version_id)]=registration(t['version'].claim_version_id,
                    'claim-version-v1','claim_version',t['version'].version_sha256,payload['version'])
                operations[key]={'signature':signature,'receipt':r.metadata_record()}
                visibility[cid]='present' if all(t[k].envelope.deletion_state=='active' for k in ('identity','version','projection')) and t['projection'].deletion_state=='active' else 'deleted'
        elif kind=='registry_metadata':
            C.exact(payload, {'ref_id','kind','record_sha256','status','description','authority_ref'}, 'registry metadata')
            C.identifier(payload['ref_id']); C.identifier(payload['authority_ref']); C.digest(payload['record_sha256'])
            C.require(payload['kind'] in ('episode','uncertainty','evidence') and payload['status'] in ('present','withheld','revoked','deleted') and
                type(payload['description']) is str and '\x00' not in payload['description'] and
                payload['ref_id'] not in current and payload['ref_id'] not in sources, 'metadata role/status collision')
            metadata[payload['ref_id']]=deepcopy(payload); visibility[payload['ref_id']]=payload['status']
        elif kind=='governance_no_commit':
            C.exact(payload, {'verdict','governance_ref','expected_current_claim_version_id','ref_id'}, 'noncommit')
            gov=governing(payload['governance_ref']); old=current.get(payload['ref_id'])
            C.require(payload['verdict'] in ('deny','defer') and gov['decision']==payload['verdict'] and
                gov['subject_ref']==payload['ref_id'] and gov['expected_current_claim_version_id']==payload['expected_current_claim_version_id'] and
                payload['expected_current_claim_version_id']==(None if old is None else old['records']['version']['claim_version_id']) and
                gov['request_digest'] is None, 'noncommit current/verdict differs')
        elif kind=='visibility_transition':
            C.exact(payload, {'ref_id','kind','expected_record_sha256','status','governance_ref'}, 'visibility transition')
            ref_id=payload['ref_id']; C.require(ref_id in visibility, 'unknown visibility identity')
            old=current.get(ref_id); source=sources.get(ref_id); meta=metadata.get(ref_id)
            identity_kind='claim' if old is not None else 'evidence' if source is not None else meta['kind']
            prior_digest=old['records']['version']['version_sha256'] if old is not None else source['registration']['evidence']['content_digest'] if source is not None else meta['record_sha256']
            gov=governing(payload['governance_ref'])
            C.require(payload['kind']==identity_kind and payload['expected_record_sha256']==prior_digest and
                payload['status'] in ('present','withheld','revoked','deleted') and gov['decision']==payload['status'] and
                gov['subject_ref']==ref_id and gov['request_digest'] is None and
                gov['expected_current_claim_version_id']==(None if old is None else old['records']['version']['claim_version_id']), 'visibility agreement differs')
            if old is not None and payload['status']=='present':
                C.require(all(old['records'][k]['envelope']['deletion_state']=='active' for k in ('identity','version','projection')) and
                    old['records']['projection']['deletion_state']=='active','inactive Claim cannot become present')
            visibility[ref_id]=payload['status']
        elif kind=='registry_target':
            C.exact(payload,{'target','registration_ref','rights_refs'},'target registration')
            row=payload['target']; C.exact(row,{'ref_id','kind','scope','authority_namespace_id','supporting_evidence_refs'},'registered target')
            C.require(type(row['supporting_evidence_refs']) is list,'target source array differs')
            target=RegisteredFormationTarget(row['ref_id'],row['kind'],C.scope(row['scope']),row['authority_namespace_id'],tuple(row['supporting_evidence_refs']))
            target.validate(); C.identifier(payload['registration_ref'])
            C.require(target.record()==row and target.scope==scope and target.authority_namespace_id==world['namespace'] and
                set(target.supporting_evidence_refs)<=set(sources) and target.ref_id not in targets,'target registration ancestry/collision differs')
            rights(payload['rights_refs'])
            targets[target.ref_id]={'target':deepcopy(row),'registration_ref':payload['registration_ref'],
                'rights_refs':deepcopy(payload['rights_refs']),'known_at_sequence':descriptor['sequence'],
                'known_at_entry_sha256':receipt.entry_sha256,'registration_sha256':C.canonical_sha256(payload)}
            registrations[('target',target.ref_id)]=registration(target.ref_id,'registered-target-v1',target.kind,
                C.canonical_sha256(payload),support=target.supporting_evidence_refs)
        elif kind=='episode_commit':
            C.exact(payload,set(E.PARTS)|{'governance_ref'},'Episode commit')
            refs={k:payload[k] for k in E.PARTS}
            raw={k:read(refs[k]) for k in ('episode','append_receipt','append_invocation','projection_profile')}
            eb=E.episode_input_binding()
            t=E.episode_transition_metadata(*(raw[k] for k in ('episode','append_receipt','append_invocation','projection_profile')),
                refs=refs,scope=scope,namespace=world['namespace'],contract_binding=eb,contract_binding_sha256=eb['record_sha256'])
            C.require(t['profile']==profile.metadata_record(),'Episode store profile differs')
            original=t['records']['episode']; eid=original['episode_id']; predecessor=original['supersedes_episode_id']
            gov=episode_governance(payload['governance_ref'])
            episode_agreement(gov,'accept',original)
            key=(t['invocation']['idempotency_namespace'],t['invocation']['idempotency_key'])
            signature={'artifacts':refs,'receipt':t['receipt'],'invocation':t['invocation']}
            if eid in episodes:
                C.require(key in episode_operations and episode_operations[key]==signature and
                    episodes[eid]['records']['episode']==original,'conflicting Episode confirmation')
            else:
                C.require(key not in episode_operations and eid not in current and eid not in sources and eid not in metadata,
                    'Episode operation/identity collision')
                C.require((predecessor is None and original['generation']==1) or
                    (predecessor in episodes and original['generation']==episodes[predecessor]['records']['episode']['generation']+1),
                    'unavailable Episode predecessor/generation')
                C.require(set(original['member_evidence_ids'])<=set(sources) and set(original['member_claim_version_ids'])<=set(versions),
                    'unavailable Episode source/Claim ancestry')
                C.require(set(original['envelope']['source_records'])-{eid}<=set(sources)|set(versions)|set(episodes),
                    'unavailable Episode envelope ancestry')
                resolutions={}; member_registrations={}
                names={'evidence':'member_evidence_ids','claim_versions':'member_claim_version_ids','candidates':'member_candidate_ids',
                    'missions':'mission_node_ids','participants':'participant_ids'}
                for role,name in names.items():
                    resolved=[]; proofs=[]
                    for member in original[name]:
                        digest=None
                        if role=='evidence':digest=sources[member]['registration']['registration_sha256']
                        elif role=='claim_versions':digest=version_digests[member]
                        elif role in ('missions','participants') and member in targets:
                            expected='mission' if role=='missions' else 'entity'
                            C.require(targets[member]['target']['kind']==expected,'supplied Episode member role differs')
                            digest=targets[member]['registration_sha256']
                        resolved.append({'ref_id':member,'status':'not_supplied' if digest is None else 'resolved','provenance_sha256':digest})
                        if digest is not None:
                            proofs.append(deepcopy(registrations[('target' if role in ('missions','participants') else role,member)]))
                    resolutions[role]=resolved
                    member_registrations[role]=proofs
                episodes[eid]={**t,'ref_id':eid,'originals':{k:{'artifact':deepcopy(refs[k]),'base64':b64encode(v).decode('ascii')} for k,v in raw.items()},
                    'known_at_sequence':descriptor['sequence'],'known_at_entry_sha256':receipt.entry_sha256,
                    'member_resolution':resolutions,'member_registrations':member_registrations}
                episode_operations[key]=deepcopy(signature)
                visibility[eid]='present' if original['envelope']['deletion_state']=='active' and original['episode_state']!='deleted' else 'deleted'
        elif kind=='episode_no_commit':
            C.exact(payload,{'episode_id','expected_predecessor_id','governance_ref'},'Episode noncommit')
            gov=episode_governance(payload['governance_ref']);C.identifier(payload['episode_id'])
            predecessor=payload['expected_predecessor_id']
            C.require(gov['action'] in ('deny','defer') and gov['episode_id']==payload['episode_id'] and
                gov['expected_predecessor_id']==predecessor and (predecessor is None or predecessor in episodes) and
                gov['episode_sha256'] is None and gov['member_ancestry_sha256'] is None,'Episode noncommit agreement differs')
        elif kind=='episode_visibility':
            C.exact(payload,{'episode_id','expected_episode_sha256','status','governance_ref'},'Episode visibility')
            C.require(payload['episode_id'] in episodes and payload['status'] in ('present','withheld','revoked','deleted'),'unknown Episode visibility')
            original=episodes[payload['episode_id']]['records']['episode'];gov=episode_governance(payload['governance_ref'])
            episode_agreement(gov,payload['status'],original)
            C.require(payload['expected_episode_sha256']==original['episode_sha256'],'Episode visibility digest differs')
            if payload['status']=='present':C.require(original['envelope']['deletion_state']=='active' and original['episode_state']!='deleted','inactive Episode cannot become present')
            visibility[payload['episode_id']]=payload['status']
        else: C.require(False,'unknown world payload kind')
        previous=record['record_sha256']; experience_head=receipt.entry_sha256; events.add(event.event_id)
    prefix=C.canonical_sha256({'cut':cut,'genesis':genesis,'records':rows})
    # Verification custody is kept outside model-visible meaning. No future suffix/branch is retained.
    proof_world={k:deepcopy(v) for k,v in world.items() if k not in ('branches','world_sha256')}
    proof_world['branches']=[{'branch_id':cut['branch_id'],'parent_cut':None,'records':deepcopy(rows)}]
    proof_world=C.seal(proof_world,'world_sha256')
    historical_proof=C.seal({'schema':'mfm-episode-historical-prefix-proof-v1','world':proof_world,'cut':deepcopy(cut),
        'original_artifacts':[{'artifact':deepcopy(ref),'base64':b64encode(cache[ref['artifact_id']]).decode('ascii')}
            for ref in pins.values()]})
    return C.seal({'schema':'mfm-world-replay-view-v2','profile':'supplied-claim-episode-prefix-v1','scope':world['scope'],
        'namespace':world['namespace'],'cut':cut,'world_prefix_sha256':prefix,'experience_head':experience_head,
        'authority_id':world['authority_profile']['authority_id'],'authority_generation':1,'authority_source_position':position,
        'current_claims':list(current.values()),'registry_metadata':list(metadata.values()),'sources':list(sources.values()),
        'visibility':visibility,'episodes':list(episodes.values()),'registry_targets':list(targets.values()),
        'historical_prefix_proof':historical_proof,
        'episode_profile':profile.metadata_record(),'episode_profile_ref':world['episode_projection_profile'],
        'supplied_governance_only':True,'authenticated_service_claimed':False,'original_artifacts':list(pins.values())},'replay_sha256')


def prefix_proof_replay(proof,*,cut):
    """Revalidate original supplied custody against the exact independently pinned cut.

    This is a pure bounded reconstruction, not a historical rights or service authentication.
    """
    C.exact(proof,{'schema','world','cut','original_artifacts','record_sha256'},'historical prefix proof')
    C.pin(proof,proof['record_sha256'],'mfm-episode-historical-prefix-proof-v1')
    C.require(proof['cut']==cut,'historical proof external cut differs')
    rows=proof['original_artifacts'];C.require(type(rows) is list and rows,'original proof inventory required')
    originals={};refs={}
    for row in rows:
        C.exact(row,{'artifact','base64'},'historical original custody');E._ref(row['artifact']);ref=row['artifact']
        C.require(ref['artifact_id'] not in originals and type(row['base64']) is str,'duplicate/malformed proof custody')
        try:raw=b64decode(row['base64'],validate=True)
        except (ValueError,TypeError) as exc:raise C.CognitiveKernelContractError('malformed historical original') from exc
        C.require(b64encode(raw).decode('ascii')==row['base64'] and len(raw)==ref['bytes'] and sha256(raw).hexdigest()==ref['file_sha256'],
            'historical original bytes differ')
        originals[ref['artifact_id']]=raw;refs[ref['artifact_id']]=ref
    def read(ref):
        C.require(refs.get(ref['artifact_id'])==ref,'historical proof artifact missing/different')
        return originals[ref['artifact_id']]
    limits=C.ConstructionLimits(max(1,cut['sequence']),max(r['bytes'] for r in refs.values()),sum(len(r) for r in originals.values()))
    world=proof['world'];binding=world_contract_binding_v2()
    rebuilt=replay_world_prefix_v2(world,world_sha256=world['world_sha256'],cut=cut,cut_sha256=cut['record_sha256'],
        read_artifact=read,limits=limits,contract_binding=binding,contract_binding_sha256=binding['record_sha256'])
    C.require(rebuilt['historical_prefix_proof']==proof,'complete historical proof differs')
    return rebuilt


